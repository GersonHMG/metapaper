"""
Experiment A comparison: grouped kernel vs. kernel height (h=16, h=21), all patients.
Reads the fold CSVs of the two all-patient runs and writes
experiments/results/a_comparison/results.md.

Both runs share patients, windows, folds and seeds, so models are compared
paired per patient (Wilcoxon signed-rank on the per-patient fold-mean F1).

    cd /home/gmarihuan/metapaper && python -m experiments.compare_a
"""

import pandas as pd
from scipy.stats import wilcoxon

from experiments.experiment_a1_kernel_height import RESULTS_ROOT, result_paths, f1_table

GROUPED_DIR = RESULTS_ROOT / "a_grouped_all"
HEIGHT_DIR = RESULTS_ROOT / "a1_kernel_height_h16_h21_all"
OUT_DIR = RESULTS_ROOT / "a_comparison"
REPORT_MD = OUT_DIR / "results.md"
HEIGHTS = [16, 21]


def load_folds():
    """All fold rows with a `model` column: 'grouped', 'h=16', 'h=21'."""
    g = pd.read_csv(result_paths(GROUPED_DIR)[1]).assign(model="grouped")
    h = pd.read_csv(result_paths(HEIGHT_DIR)[1])
    h = h[h["kernel_height"].isin(HEIGHTS)]
    h = h.assign(model="h=" + h["kernel_height"].astype(str)).drop(columns="kernel_height")
    return pd.concat([g, h], ignore_index=True)


def paired_table(pm, windows, models):
    """Grouped vs. each kernel height: mean F1 difference, wins and Wilcoxon p per window."""
    lines = ["| Window | " + " | ".join(f"grouped − {m} | grouped wins | p" for m in models[1:]) + " |",
             "|---|" + "---|---|---|" * (len(models) - 1)]
    for w in windows:
        cells = []
        for m in models[1:]:
            pair = pm.loc[w, ["grouped", m]].dropna()
            d = pair["grouped"] - pair[m]
            p = wilcoxon(pair["grouped"], pair[m]).pvalue
            cells += [f"{d.mean():+.3f}", f"{(d > 0).sum()} / {len(d)}",
                      "<0.001" if p < 0.001 else f"{p:.3f}"]
        lines.append(f"| {w} s | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def per_patient_table(pm, windows, models):
    """Rows patient × model (the layout planned in experiment_a.md), best model per
    patient and window in bold."""
    lines = ["| Patient | Model | " + " | ".join(f"{w} s" for w in windows) + " |",
             "|---|---|" + "---|" * len(windows)]
    for p in pm.index.get_level_values("patient").unique():
        best = {w: pm.loc[(w, p)].max() if (w, p) in pm.index else None for w in windows}
        for m in models:
            cells = []
            for w in windows:
                if (w, p) not in pm.index:
                    cells.append("—")
                    continue
                v = pm.loc[(w, p), m]
                cells.append(f"**{v:.3f}**" if v == best[w] else f"{v:.3f}")
            lines.append(f"| {p} | {m} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main():
    df = load_folds()
    models = ["grouped"] + [f"h={h}" for h in HEIGHTS]
    windows = sorted(df["window_sec"].unique())

    fold_mean = df.groupby(["window_sec", "patient", "model"])["f1"].mean()
    pm = fold_mean.unstack("model")[models]                 # (window, patient) x model
    by_window = pm.groupby("window_sec")
    auroc = (df.groupby(["window_sec", "patient", "model"])["auroc"].mean()
             .groupby(["window_sec", "model"]).mean().unstack()[models])
    n_patients = df["patient"].nunique()

    parts = [
        "# Experiment A: Grouped kernel vs. kernel height (all patients)\n",
        f"`SpatialNet(spatial=\"grouped\")` vs. `SpatialNet(spatial=\"height\", kernel_height=h)`, "
        f"h ∈ {{{', '.join(map(str, HEIGHTS))}}}. Recording CV (5 folds, leave-one-recording-out "
        f"when a patient has fewer recordings), {n_patients} patients, same folds and seeds for "
        "every model. chb16 is excluded at 10 s. See `experiments/experiment_a.md`.\n",
        f"Sources: `{GROUPED_DIR.name}/`, `{HEIGHT_DIR.name}/`. "
        "Generated by `experiments/compare_a.py`.\n",
        "## F1, mean over patients\n",
        f1_table(by_window.mean(), by_window.var(),
                 "Mean of the per-patient fold means ± variance across patients. "
                 "Best mean per window in bold.", cols=models, label="{}"),
        "## Median F1 over patients\n",
        "| Window | " + " | ".join(models) + " |",
        "|---|" + "---|" * len(models),
        *[f"| {w} s | " + " | ".join(f"{v:.3f}" for v in by_window.median().loc[w]) + " |"
          for w in windows],
        "",
        "## AUROC, mean over patients\n",
        "| Window | " + " | ".join(models) + " |",
        "|---|" + "---|" * len(models),
        *[f"| {w} s | " + " | ".join(f"{v:.3f}" for v in auroc.loc[w]) + " |" for w in windows],
        "",
        "## Paired comparison per patient\n",
        "Difference in mean F1 (positive = grouped better), number of patients where grouped "
        "is better, and the two-sided Wilcoxon signed-rank p-value over patients. "
        "No correction for multiple comparisons.\n",
        paired_table(pm, windows, models),
        "## Per patient\n",
        "F1 averaged over folds. Best model per patient and window in bold.\n",
        per_patient_table(pm, windows, models),
    ]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_MD.write_text("\n".join(parts))
    print(REPORT_MD.read_text())


if __name__ == "__main__":
    main()
